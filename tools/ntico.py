VGA = [(0,0,0), (128,0,0), (0,128,0), (128,128,0), (0,0,128), (128,0,128), (0,128,128),
       (192,192,192), (128,128,128), (255,0,0), (0,255,0), (255,255,0), (0,0,255),
       (255,0,255), (0,255,255), (255,255,255)]
BW = [(0,0,0), (255,255,255)]

def rows(s):
    r = s.split()
    assert all(len(x) == len(r) for x in r), 'not square'
    return r

def image(pic, bits):
    """the icon's picture as NT reads it: a DIB of twice the height (the colors,
    then the AND mask: 1 is transparent), rows from the bottom up"""
    n = len(pic)
    pal = VGA if bits == 4 else BW
    xor = b''; andm = b''
    for row in reversed(pic):
        v = [0 if c == '.' else int(c, 16) // (15 if bits == 1 else 1) for c in row]
        if bits == 4:
            b = bytes(v[i] << 4 | v[i + 1] for i in range(0, n, 2))
        else:
            b = bytes(sum(v[i + j] << (7 - j) for j in range(8)) for i in range(0, n, 8))
        m = bytes(sum((row[i + j] == '.') << (7 - j) for j in range(8)) for i in range(0, n, 8))
        xor += b + bytes(-len(b) % 4)
        andm += m + bytes(-len(m) % 4)
    hdr = struct.pack('<IiiHHIIiiII', 40, n, 2 * n, 1, bits, 0, len(xor) + len(andm), 0, 0, 0, 0)
    return hdr + b''.join(bytes((b, g, r, 0)) for r, g, b in pal) + xor + andm

pics = [(rows(C32), 4), (rows(C16), 4), (rows(M32), 1)]
for pic, bits in pics:
    assert bits == 4 or set(''.join(pic)) <= set('0f.'), 'black and white has only 0, f, .'
    print('\n'.join(pic) + '\n')
if len(sys.argv) > 1:
    data = [image(p, b) for p, b in pics]
    ico = struct.pack('<HHH', 0, 1, len(data))
    off = 6 + 16 * len(data)
    for (p, b), d in zip(pics, data):
        ico += struct.pack('<BBBBHHII', len(p), len(p), 1 << b, 0, 1, b, len(d), off)
        off += len(d)
    open(sys.argv[1], 'wb').write(ico + b''.join(data))
